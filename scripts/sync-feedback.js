#!/usr/bin/env node
/**
 * Inline scripts/feedback-widget.html into the pages that carry it.
 *
 *   node scripts/sync-feedback.js            write
 *   node scripts/sync-feedback.js --check    exit non-zero on drift
 *
 * Same pattern, and the same reason, as scripts/sync-engine.js and
 * scripts/sync-play-data.js: a <script src> cannot be read when the page is
 * opened as a downloaded local file or run inside the artifact viewer, so the
 * block has to be literally present in each page. One source, inlined, and a
 * --check that fails when the copies drift.
 *
 * NOT on learn.html. That page is the boys', and a twelve-year-old filing
 * issues on a public repo is not what this is for.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'scripts', 'feedback-widget.html');
// designer.html is edited by hand. index.html is GENERATED from
// bridge/combined-shell.html by bridge/build-combined.mjs, so the widget goes
// into the template -- writing it into index.html directly would be wiped by
// the next rebuild, which is the sort of thing that gets discovered a month
// later when the button quietly disappears.
const PAGES = ['designer.html', 'bridge/combined-shell.html'];
const OPEN = '<!-- feedback-widget: generated by scripts/sync-feedback.js, do not edit here -->';
const CLOSE = '<!-- /feedback-widget -->';

const check = process.argv.includes('--check');
const widget = fs.readFileSync(SRC, 'utf8').trim();
const block = OPEN + '\n' + widget + '\n' + CLOSE;

let drift = 0, wrote = 0;
for (const page of PAGES) {
  const file = path.join(ROOT, page);
  let html = fs.readFileSync(file, 'utf8');

  const i = html.indexOf(OPEN);
  const j = html.indexOf(CLOSE);
  let next;

  if (i === -1 || j === -1) {
    // First time: put it immediately before </body> so nothing on the page can
    // be laid out around it and the FAB is the last thing in the stacking order.
    // Before </body> where there is one. combined-shell.html has no closing
    // tags at all -- browsers close them -- so there the block goes at the end.
    const at = html.lastIndexOf('</body>');
    next = at === -1 ? html.replace(/\s*$/, '\n') + block + '\n'
                     : html.slice(0, at) + block + '\n' + html.slice(at);
  } else {
    next = html.slice(0, i) + block + html.slice(j + CLOSE.length);
  }

  if (next === html) continue;
  if (check) { console.error('DRIFT  ' + page + ' does not match scripts/feedback-widget.html'); drift++; continue; }
  fs.writeFileSync(file, next);
  wrote++;
}

if (check) {
  if (drift) { console.error('\n' + drift + ' page(s) have drifted. Run: node scripts/sync-feedback.js'); process.exit(1); }
  console.log('In sync — the lightbulb is identical on ' + PAGES.length + ' pages.');
} else {
  console.log(wrote ? 'Updated ' + wrote + ' page(s).' : 'Already in sync.');
}

// The print hide list is explicit in designer.html, and CLAUDE.md records that
// an element left out of it prints -- that is how the game-day bar leaked onto
// the normal screen. The widget carries its own @media print rule, so this is a
// belt-and-braces check rather than an edit.
for (const page of PAGES.concat(['index.html'])) {
  const file = path.join(ROOT, page);
  if (!fs.existsSync(file)) continue;
  const html = fs.readFileSync(file, 'utf8');
  if (html.includes('#fbFab') && !/@media print\{#fbFab,#fbPanel\{display:none!important\}\}/.test(html)) {
    console.error('WARNING  ' + page + ' carries the widget but not its print rule.');
    process.exit(1);
  }
}
